const pressById = new Map(PRESSES.map((p) => [p.id, p]));
const printById = new Map(PRINTS.map((p) => [p.id, p]));

export const getPress = (id) => pressById.get(id);
export const getPrint = (id) => printById.get(id);
export const inkOf = (id) => INKS[id];
export const paperOf = (print) => PAPERS[print.paper];
export const remaining = (print) => Math.max(0, print.edition - print.sold);
export const printsByPress = (pressId) => PRINTS.filter((p) => p.press === pressId);

// Inks that at least one listing uses, in the order they are declared above.
export const INKS_IN_USE = Object.keys(INKS).filter((id) => PRINTS.some((p) => p.inks.includes(id)));

export const formatSize = (print) => `${fmtCm(print.size[0])} × ${fmtCm(print.size[1])} cm`;
const fmtCm = (n) => (Number.isInteger(n) ? String(n) : n.toFixed(1));

const euro = new Intl.NumberFormat('en-IE', { style: 'currency', currency: 'EUR', maximumFractionDigits: 0 });
export const formatPrice = (amount) => euro.format(amount);

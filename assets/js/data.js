// Framing is priced by the longest side of the sheet, in cm.
export function framePrice(print, finish) {
  if (!finish || finish === 'none') return 0;
  const long = Math.max(...print.size);
  const base = long <= 30 ? 34 : long <= 42 ? 46 : long <= 50 ? 58 : 82;
  return finish === 'walnut' ? base + 12 : base;
}

